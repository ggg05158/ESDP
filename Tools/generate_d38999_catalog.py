"""Generate the D38999 in-assembly catalog from the master workbook.

This utility is only needed when the master workbook changes. The generated
C# file is what the application compiles and uses at runtime.
"""

from __future__ import annotations

import base64
import gzip
import json
from pathlib import Path

from openpyxl import load_workbook


ROOT = Path(__file__).resolve().parents[1]
WORKBOOK = ROOT / "Resources" / "D38999_connector_data" / "D38999_Master.xlsx"
OUTPUT = ROOT / "D38999CatalogData.g.cs"


def rows_by_header(sheet):
    values = sheet.iter_rows(values_only=True)
    headers = [str(value).strip() if value is not None else "" for value in next(values)]
    for values_row in values:
        row = {headers[index]: value for index, value in enumerate(values_row) if index < len(headers)}
        yield row


def text(value) -> str:
    return "" if value is None else str(value).strip()


def number(value) -> int:
    if value is None or value == "":
        return 0
    return round(float(value))


def build_payload() -> dict:
    workbook = load_workbook(WORKBOOK, read_only=False, data_only=True)
    try:
        arrangements = []
        for row in rows_by_header(workbook["Insert_Arrangements"]):
            arrangement_id = text(row.get("Arrangement_ID"))
            if not arrangement_id:
                continue
            arrangements.append([
                arrangement_id,
                number(row.get("Shell_Size")),
                text(row.get("Insert")),
                number(row.get("Total_Contacts")),
                [number(row.get(f"Qty_{size}")) for size in ("23", "22D", "20", "16", "12", "10", "8")],
                text(row.get("Service_Rating")),
                text(row.get("Category")),
                text(row.get("Special_Contact_Note")),
                text(row.get("Firewall_Allowed")),
                text(row.get("Planned_Image_File")),
                text(row.get("Image_Status")),
                text(row.get("Visual_Source_Arrangement")),
            ])

        configurations = []
        for row in rows_by_header(workbook["Valid_Configurations"]):
            arrangement_id = text(row.get("Arrangement_ID"))
            if not arrangement_id:
                continue
            configurations.append([
                text(row.get("Part_Number_Pattern")),
                text(row.get("Slash")),
                text(row.get("Connector_Type")),
                number(row.get("Shell_Size")),
                text(row.get("Insert")),
                arrangement_id,
                text(row.get("Allowed_Classes")),
                text(row.get("Allowed_Contact_Styles")),
                text(row.get("Allowed_Keying")),
            ])

        rules = []
        for row in rows_by_header(workbook["Contact_Wire_Rules"]):
            rule_id = text(row.get("Rule_ID"))
            if not rule_id:
                continue
            gauges = [
                int(token.strip())
                for token in text(row.get("Allowed_AWG")).split("|")
                if token.strip()
            ]
            rules.append([
                rule_id,
                text(row.get("Insert_Contact_Size")),
                text(row.get("Contact_Category")),
                gauges,
                text(row.get("New_Design_Status")),
                text(row.get("Cable_Spec")),
            ])
        return {"a": arrangements, "c": configurations, "r": rules}
    finally:
        workbook.close()


def render_source(payload: dict) -> str:
    json_bytes = json.dumps(payload, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    encoded = base64.b64encode(gzip.compress(json_bytes, compresslevel=9, mtime=0)).decode("ascii")
    wrapped = "\n".join(encoded[index:index + 120] for index in range(0, len(encoded), 120))
    return f'''// <auto-generated />
// Generated from Resources/D38999_connector_data/D38999_Master.xlsx.
// Re-run Tools/generate_d38999_catalog.py only when the source workbook changes.

using System.IO;
using System.IO.Compression;
using System.Text.Json;

namespace ESDP
{{
    internal sealed class D38999CatalogSnapshot
    {{
        public required IReadOnlyList<D38999InsertArrangement> Arrangements {{ get; init; }}
        public required IReadOnlyList<D38999Configuration> Configurations {{ get; init; }}
        public required IReadOnlyList<D38999ContactRule> ContactRules {{ get; init; }}
    }}

    internal static class D38999CatalogData
    {{
        private static readonly string[] ContactSizes = {{ "23", "22D", "20", "16", "12", "10", "8" }};

        internal static D38999CatalogSnapshot Load()
        {{
            byte[] compressed = Convert.FromBase64String(PayloadBase64);
            using var input = new MemoryStream(compressed, writable: false);
            using var gzip = new GZipStream(input, CompressionMode.Decompress);
            using var document = JsonDocument.Parse(gzip);
            var root = document.RootElement;

            var arrangements = new List<D38999InsertArrangement>();
            foreach (var row in root.GetProperty("a").EnumerateArray())
            {{
                var item = new D38999InsertArrangement
                {{
                    ArrangementId = row[0].GetString() ?? "",
                    ShellSize = row[1].GetInt32(),
                    Insert = row[2].GetString() ?? "",
                    TotalContacts = row[3].GetInt32(),
                    ServiceRating = row[5].GetString() ?? "",
                    Category = row[6].GetString() ?? "",
                    SpecialContactNote = row[7].GetString() ?? "",
                    FirewallAllowed = row[8].GetString() ?? "",
                    PlannedImageFile = row[9].GetString() ?? "",
                    ImageStatus = row[10].GetString() ?? "",
                    VisualSourceArrangement = row[11].GetString() ?? ""
                }};
                int index = 0;
                foreach (var count in row[4].EnumerateArray())
                    item.ContactCounts[ContactSizes[index++]] = count.GetInt32();
                arrangements.Add(item);
            }}

            var configurations = new List<D38999Configuration>();
            foreach (var row in root.GetProperty("c").EnumerateArray())
            {{
                configurations.Add(new D38999Configuration
                {{
                    PartNumberPattern = row[0].GetString() ?? "",
                    Slash = row[1].GetString() ?? "",
                    ConnectorType = row[2].GetString() ?? "",
                    ShellSize = row[3].GetInt32(),
                    Insert = row[4].GetString() ?? "",
                    ArrangementId = row[5].GetString() ?? "",
                    AllowedClasses = row[6].GetString() ?? "",
                    AllowedContactStyles = row[7].GetString() ?? "",
                    AllowedKeying = row[8].GetString() ?? ""
                }});
            }}

            var rules = new List<D38999ContactRule>();
            foreach (var row in root.GetProperty("r").EnumerateArray())
            {{
                var rule = new D38999ContactRule
                {{
                    RuleId = row[0].GetString() ?? "",
                    InsertContactSize = row[1].GetString() ?? "",
                    ContactCategory = row[2].GetString() ?? "",
                    NewDesignStatus = row[4].GetString() ?? "",
                    CableSpec = row[5].GetString() ?? ""
                }};
                foreach (var gauge in row[3].EnumerateArray())
                    rule.AllowedAwg.Add(gauge.GetInt32());
                rules.Add(rule);
            }}

            return new D38999CatalogSnapshot
            {{
                Arrangements = arrangements,
                Configurations = configurations,
                ContactRules = rules
            }};
        }}

        private const string PayloadBase64 = """
{wrapped}
""";
    }}
}}
'''


def main() -> None:
    payload = build_payload()
    OUTPUT.write_text(render_source(payload), encoding="utf-8", newline="\n")
    print(
        f"Generated {OUTPUT.name}: "
        f"{len(payload['a'])} arrangements, "
        f"{len(payload['c'])} configurations, "
        f"{len(payload['r'])} contact rules"
    )


if __name__ == "__main__":
    main()
